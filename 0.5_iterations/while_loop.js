// WHILE LOOP

let index = 0
while (index <= 15) {
    console.log(`The value of index is ${index}`);
    index = index + 3
}

let myArray = ["spiderman", "thor", "hulk", "iron man"]
let arr = 0
while (arr < myArray.length) {
    console.log(`Value is ${myArray[arr]}`);
    arr = arr + 1
}

///DO WHILE LOOP
let point = 10
do {
    console.log(`You have ${point} point left.`);
    point++

} while (point <= 9);